#!/usr/bin/env python3
"""Build worker-site.js from dist/ for the nam-vs-nu-live Cloudflare Worker.

Regenerates the inline Worker (HTML + 1 JS + 1 CSS as strings, same format
as the previously deployed worker-site.js). Run after `npm run build`:
    python3 build-worker-site.js
Then deploy with:
    python3 deploy-worker.py --account 080fccb73e5e0167ed2aa0c442586d44 \\
        --file worker-site.js --name nam-vs-nu-live
Do NOT hand-edit worker-site.js — it is generated by this script.
"""
import glob
import json
import os

ROOT = os.path.dirname(os.path.abspath(__file__))
DIST = os.path.join(ROOT, "dist")


def main():
    html = open(os.path.join(DIST, "index.html"), encoding="utf-8").read()
    js_files = sorted(glob.glob(os.path.join(DIST, "assets", "*.js")))
    css_files = sorted(glob.glob(os.path.join(DIST, "assets", "*.css")))
    assert len(js_files) == 1, js_files
    assert len(css_files) == 1, css_files
    js_path = "/assets/" + os.path.basename(js_files[0])
    css_path = "/assets/" + os.path.basename(css_files[0])
    js = open(js_files[0], encoding="utf-8").read()
    css = open(css_files[0], encoding="utf-8").read()
    parts = [
        "// NAM vs NỮ LIVE 2D — static site served as a Cloudflare Worker.",
        "// dist/ (index.html + 1 JS + 1 CSS) inlined as strings; no build step at runtime.",
        "// Regenerated by build-worker-site.py — do not hand-edit.",
        f"const HTML = {json.dumps(html)};",
        f"const JS = {json.dumps(js)};",
        f"const CSS = {json.dumps(css)};",
        "const ASSETS = {",
        f'  "{js_path}": ["text/javascript; charset=utf-8", JS],',
        f'  "{css_path}": ["text/css; charset=utf-8", CSS],',
        "};",
        r"""export default {
  async fetch(req) {
    const url = new URL(req.url);
    let path = url.pathname;
    while (path.length > 1 && path.endsWith("/")) path = path.slice(0, -1);
    if (path === "/" || path === "/index.html" || path === "/admin") {
      return new Response(HTML, { headers: { "content-type": "text/html; charset=utf-8", "cache-control": "no-cache" } });
    }
    const asset = ASSETS[path];
    if (asset) {
      return new Response(asset[1], { headers: { "content-type": asset[0], "cache-control": "public, max-age=31536000, immutable" } });
    }
    // Ảnh quà TikTok (/gifts/*.webp) + GLB nhân vật (/characters/*.glb)
    // + tiếng đánh (/sounds/*.mp3) không nhúng vào worker (vượt giới hạn
    // ~1MB của Worker miễn phí) — lấy từ bản live trên Render (có file
    // thật trong repo sau khi upload qua web GitHub). Chỉ proxy khi Render
    // trả đúng kiểu file (tránh nuốt nhầm trang index.html khi file chưa
    // được upload).
    if (path.startsWith("/gifts/") || path.startsWith("/characters/") || path.startsWith("/sounds/")) {
      const r = await fetch("https://nam-vs-nu-live.onrender.com" + path);
      const ct = r.headers.get("content-type") || "";
      if (r.ok && (ct.startsWith("image/") || ct.startsWith("audio/") || ct.includes("gltf") || ct.includes("octet-stream"))) {
        return new Response(r.body, { headers: { "content-type": ct, "cache-control": "public, max-age=3600" } });
      }
    }
    return new Response("Not found", { status: 404 });
  },
};""",
    ]
    out = os.path.join(ROOT, "worker-site.js")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(parts) + "\n")
    print(f"worker-site.js written: {js_path} + {css_path} ({os.path.getsize(out)} bytes)")


if __name__ == "__main__":
    main()
